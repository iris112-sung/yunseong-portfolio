import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser = await chromium.launch({channel:'chrome'});
const page = await browser.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await fs.mkdir('test-results',{recursive:true});
const url=process.env.TEST_URL || 'http://127.0.0.1:5173/';
async function colors(buffer) {
 return page.evaluate(async data=>{const image=new Image();image.src=`data:image/png;base64,${data}`;await image.decode();const canvas=document.createElement('canvas');canvas.width=image.width;canvas.height=image.height;const ctx=canvas.getContext('2d');ctx.drawImage(image,0,0);const pixels=ctx.getImageData(0,0,canvas.width,canvas.height).data;const colors=new Set();for(let i=0;i<pixels.length;i+=80)colors.add(`${pixels[i]},${pixels[i+1]},${pixels[i+2]}`);return colors.size;},buffer.toString('base64'));
}
for(const [width,height] of [[1440,900],[390,844]]) {
 await page.setViewportSize({width,height});
 await page.goto(url);
 await page.locator('.page-loader').waitFor({state:'detached',timeout:15000});
 await page.locator('.signature-sculpture[data-ready=true]').waitFor();
 await page.waitForTimeout(300);
 await expect(page.locator('header')).toHaveCSS('opacity','0');
 await expect(page.locator('header')).toHaveAttribute('inert','');
 await page.evaluate(()=>window.scrollTo({top:innerHeight*0.3,behavior:'instant'}));
 await page.waitForTimeout(150);
 const partial=await page.locator('header').evaluate(el=>({opacity:Number(getComputedStyle(el).opacity),filter:getComputedStyle(el).filter}));
 assert(partial.opacity>0 && partial.opacity<1,'Header should fade in progressively');
 assert(partial.filter!=='blur(0px)','Header should be blurred mid-reveal');
 await page.screenshot({path:`test-results/header-partial-${width}.png`});
 await page.evaluate(()=>window.scrollTo({top:innerHeight*0.75,behavior:'instant'}));
 await expect(page.locator('header')).toHaveCSS('opacity','1');
 await expect(page.locator('header')).toHaveCSS('filter','blur(0px)');
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 await expect(page.locator('header')).toHaveCSS('opacity','0');
 const canvas=page.locator('.signature-sculpture canvas');
 const first=await canvas.screenshot();
 assert(await colors(first)>100,'Blank sculpture canvas');
 await page.waitForTimeout(350);
 assert(!first.equals(await canvas.screenshot()),'Static sculpture');
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:`test-results/experience-intro-${width}.png`});
 await page.getByRole('button',{name:'소개 문구 보기'}).click();
 await expect(page.locator('.intro-statement')).toHaveCSS('opacity','1',{timeout:5000});
 await page.screenshot({path:`test-results/experience-statement-${width}.png`});
 await page.locator('#projects').scrollIntoViewIfNeeded();
 await page.waitForTimeout(2500);
 assert(await colors(await page.locator('.flex-carousel canvas').screenshot())>60,'Blank carousel');
 await page.getByRole('tab',{name:'Reply',exact:true}).click();
 await expect(page.locator('#project-panel h3')).toHaveText('댓글의 의미를 지키는 AI');
 await page.getByRole('button',{name:'다음 프로젝트',exact:true}).click();
 await expect(page.locator('#project-panel h3')).toHaveText('모두를 위한 음성 주문');
 await page.getByRole('button',{name:'자세히 보기',exact:true}).click();
 await expect(page.locator('#dialog-title')).toHaveText('Speaki');
 await expect(page.locator('dialog')).toContainText('Whisper 비교 실험');
 await expect(page.locator('dialog')).toContainText('2026.08');
 await page.keyboard.press('Escape');
 await page.locator('.flex-carousel').focus();
 await page.keyboard.press('ArrowLeft');
 await expect(page.locator('#project-panel h3')).toHaveText('댓글의 의미를 지키는 AI');
 await page.getByRole('button',{name:'자세히 보기',exact:true}).click();
 await expect(page.locator('dialog')).toBeVisible();
 await expect(page.locator('#dialog-title')).toHaveText('Reply');
 await page.keyboard.press('Escape');
 await page.screenshot({path:`test-results/experience-projects-${width}.png`});
 await page.getByRole('button',{name:'EN',exact:true}).click();
 await expect(page.locator('#project-panel h3')).toHaveText('A more thoughtful comment section');
 await page.getByRole('button',{name:'KR',exact:true}).click();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 console.log(`PASS ${width}: sculpture pixels/motion, scroll reveal, carousel, tabs, keyboard, dialog, languages`);
}
await page.emulateMedia({reducedMotion:'reduce'});
await page.goto(url);
await page.locator('.page-loader').waitFor({state:'detached'});
await expect(page.locator('.intro-experience')).toHaveClass(/is-reduced/);
await expect(page.locator('.intro-statement h1')).toBeVisible();
await page.goto(`${url}#/reviews`);
await expect(page.locator('header')).toHaveCSS('opacity','1');
await expect(page.locator('header')).not.toHaveAttribute('inert','');
assert.deepEqual(errors,[]);
console.log('PASS: reduced motion and no runtime exceptions');
await browser.close();
